/**
 * BMUX Command Registry - the single source of truth for commands.
 *
 * Every way of running a command in BMUX resolves here:
 *   - toolbar buttons      -> the command line they are named after
 *   - debug console        -> whatever you type
 *   - `:` line (Control Mode) -> whatever you type
 *   - per-pane inputs      -> whatever you type, scoped to that pane
 *   - Control Mode / Ctrl+b keys -> BMUX_KEYBINDINGS[<mode>][<key>]
 *
 * `content/main.js` holds no command definitions, no help text and no
 * key-to-action switch. It only parses a line, looks the name up here and
 * calls `execute` with an `api` object.
 *
 * Command shape:
 *
 *     'name': {
 *         scope: 'overlay' | 'pane',
 *         description: 'One line, shown by help',
 *         usage: 'name <required> [optional]',
 *         execute: async function (api, args) { return 'text to display'; }
 *     }
 *
 * `api` is supplied by main.js:
 *     api.client  - the top-frame BMUXClient (layout, pane and overlay primitives)
 *     api.pane    - the pane the command was invoked for, or the active pane
 *     api.log(msg)- append a line to the debug console
 *
 * Overlay commands manage the whole overlay and must not assume a pane exists.
 * Pane commands act on one pane's iframe / DOM and check api.pane themselves.
 *
 * To add a command: add one entry to BMUX_COMMANDS. It is then available from
 * every entry point, listed by `help`, and testable on its own.
 */

/**
 * Split args into flags, flag values and positional arguments, the way the
 * inspection commands are documented: `list-cookies --name session -j` has no
 * positionals, `set-cookie a=b --path /x` has one.
 */
function bmuxTakeFlags(args, valueFlags) {
    const valued = valueFlags || [];
    const parsed = { flags: {}, values: {}, rest: [], unknown: [] };

    for (let i = 0; i < args.length; i++) {
        const arg = String(args[i]);

        if (valued.indexOf(arg) !== -1) {
            parsed.values[arg] = args[i + 1] === undefined ? '' : String(args[++i]);
            continue;
        }

        if (arg.length > 1 && arg.charAt(0) === '-') {
            parsed.flags[arg] = true;
            continue;
        }

        parsed.rest.push(arg);
    }

    return parsed;
}

/** `name=value`, as used by set-cookie and set-storage. */
function bmuxSplitAssignment(text) {
    const value = String(text == null ? '' : text);
    const index = value.indexOf('=');
    if (index === -1) return null;
    return { name: value.slice(0, index), value: value.slice(index + 1) };
}

/** Epoch seconds -> `YYYY-MM-DD`, or `session` for a cookie without an expiry. */
function bmuxCookieExpiry(cookie) {
    if (!cookie || typeof cookie.expirationDate !== 'number') return 'session';
    try {
        return new Date(cookie.expirationDate * 1000).toISOString().slice(0, 10);
    } catch (error) {
        return 'unknown';
    }
}

/** Netscape jar text, which curl, wget and yt-dlp all accept. */
function bmuxCookiesToNetscape(cookies, hostLabel) {
    const lines = ['# Netscape HTTP Cookie File', '# Generated by BMUX (' + (hostLabel || 'pane') + ')', ''];

    cookies.forEach((cookie) => {
        const domain = cookie.hostOnly ? cookie.domain
            : (String(cookie.domain).charAt(0) === '.' ? cookie.domain : '.' + cookie.domain);
        lines.push([
            domain,
            cookie.hostOnly ? 'FALSE' : 'TRUE',
            cookie.path || '/',
            cookie.secure ? 'TRUE' : 'FALSE',
            cookie.expirationDate ? Math.floor(cookie.expirationDate) : 0,
            cookie.name,
            String(cookie.value == null ? '' : cookie.value).replace(/\t/g, ' ')
        ].join('\t'));
    });

    return lines.join('\n');
}

